// The designer copies it into "My Baseline" and changes every value to match
// how they actually work. The estimation engine only ever reads My Baseline.
//
// Hours are design hours for one function at the given level, including its
// typical screens and states. Tags tell complexity rules which functions a
// signal actually creates extra design work for (so nothing is double counted):
//   entry          – entry points; never counted inside a task flow
//   roleSensitive  – changes when different user types see or do different things
//   stateful       – has items that move through statuses
//   dataHeavy      – grows with how much information is entered, shown or managed
//   transactional  – contains commitments (orders, bookings, submissions)

